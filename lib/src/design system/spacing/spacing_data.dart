import '../../helpers/helpers.dart';

/// A utility class for defining spacing values commonly used in layouts.
class SpacingData {
  // Private constructor to prevent instantiation.
  SpacingData._();

  /// Represents extra small spacing with a value of 4.0.
  static final double extraSmallSpacing = Dimensions.xs;

  /// Represents small spacing with a value of 8.0.
  static final double smallSpacing = Dimensions.s;

  /// Represents large spacing with a value of 16.0.
  static final double largeSpacing = Dimensions.l;

  /// Represents extra large spacing with a value of 32.0.
  static final double extraLargeSpacing = Dimensions.xl;
}
